# ── Code generation (pure Python, no NumPy) ────────────────────────────────────

def _taps_vector(oct_val: int) -> list[int]:
    """Feedback-tap vector a_{i,j} for j=1..14 from octal notation (ICD §3.4.1):
    bits counted right-to-left from LSB j=0; return j=1..R (a_0 unused, a_R=1)."""
    return [(oct_val >> j) & 1 for j in range(1, 15)]


def _start_vector(oct_val: int) -> list[int]:
    """Register start-value vector s_{i,j} for j=1..14 from octal notation:
    bits counted right-to-left from LSB starting at j=1 (ICD §3.4.1)."""
    return [(oct_val >> (j - 1)) & 1 for j in range(1, 15)]


def primary_code(component: str, svid: int) -> list[int]:
    """Return the 10230-chip Galileo E5 primary code for a component
    ('E5a-I'|'E5a-Q'|'E5b-I'|'E5b-Q') and SVID (1..50), as a list of 0/1.

    Two 14-bit LFSRs: base register 1 seeded all-ones, base register 2 seeded
    with the per-code start value. Output chip = reg1[14] XOR reg2[14]; the new
    bit shifts into cell 1 (feedback = XOR of tapped cells). Registers are reset
    after 10230 chips (truncation to primary length)."""
    if not 1 <= svid <= 50:
        raise ValueError(f"SVID must be 1..50, got {svid}")
    t1_oct, t2_oct = TAPS[component]
    tap1, tap2 = _taps_vector(t1_oct), _taps_vector(t2_oct)
    c1 = [1] * 14
    c2 = _start_vector(S2_BY_COMPONENT[component][svid])
    out: list[int] = []
    for _ in range(PRIMARY_LEN):
        out.append(c1[13] ^ c2[13])
        fb1 = 0
        fb2 = 0
        for j in range(14):
            fb1 ^= tap1[j] & c1[j]
            fb2 ^= tap2[j] & c2[j]
        c1 = [fb1] + c1[:13]
        c2 = [fb2] + c2[:13]
    return out


def _hex_bits(hexstr: str, length: int) -> list[int]:
    """Hex code sequence → list of 0/1, MSB-first, first chip = leftmost bit
    (ICD §3.4.1.1 / §3.5.1 convention), truncated to `length` chips."""
    nbits = len(hexstr) * 4
    v = int(hexstr, 16)
    bits = [(v >> (nbits - 1 - i)) & 1 for i in range(nbits)]
    return bits[:length]


def secondary_code(band: str, channel: str, svid: int) -> list[int]:
    """Secondary (overlay) code for a band ('E5a'|'E5b'), channel
    ('data'|'pilot') and SVID, as a list of 0/1."""
    hexstr, length = BANDS[band]["sec_data" if channel == "data" else "sec_pilot"](svid)
    return _hex_bits(hexstr, length)


