#!/usr/bin/env python3
"""
Galileo E5a / E5b transmitter for GNU Radio + UHD (Ettus B200-mini family).

Purpose
───────
Transmit ONE spectrally-correct Galileo E5 sideband — E5a (1176.45 MHz) or
E5b (1207.14 MHz) — as a QPSK(10) signal: the data component on I, the pilot
component on Q, both BPSK-modulated with the real 10.23 Mcps tiered ranging
codes from the Galileo OS SIS ICD (Issue 2.2, Nov 2025). This is a single
sideband, NOT the full E5 AltBOC(15,10); it reproduces the correct ~20 MHz
BPSK(10) main lobe of one E5 half.

⚠  RF SAFETY / LEGAL: E5a/E5b are live GNSS bands. Transmit ONLY into a
   shielded / conducted setup (cable + attenuators into a receiver or spectrum
   analyser) that you are LICENSED / AUTHORISED to use. Radiating a GNSS code
   over the air can jam or spoof real receivers and is illegal in most places.

Signal construction (per ICD §3)
────────────────────────────────
Each E5 sideband carries two orthogonal components at 10.23 Mcps:

    E5a-I  data channel  ┐                      E5b-I  data channel  ┐
    E5a-Q  pilot channel ┘ QPSK on I/Q          E5b-Q  pilot channel ┘

Every component is a *tiered* code: a length-10230 primary code, generated by
two 14-bit LFSRs (output = reg1 XOR reg2, register 1 seeded all-ones, register
2 per-code start value, both reset after 10230 chips), overlaid chip-by-epoch
with a secondary code:

    component      primary   secondary            tiered period
    E5a-I (data)   10230     CS201  (20 chip)      20 ms
    E5a-Q (pilot)  10230     CS100n (100 chip)     100 ms
    E5b-I (data)   10230     CS41   (4 chip)       4 ms
    E5b-Q (pilot)  10230     CS100(n+50) (100)     100 ms

The full repeating period of each sideband is therefore 100 ms (an integer
number of every component's tiered period). At 40.92 MS/s that is exactly
4 092 000 complex samples (~32 MB), precomputed once into /dev/shm and replayed
with blocks.file_source(repeat=True) — so the whole 100 ms tiered structure is
bit-exact and loops with no seam. No navigation data is modulated (data symbol
held constant) to give a clean, deterministic ranging spectrum.

The primary generator, secondary codes and code→component assignment are all
validated bit-exact against the ICD's published check values — the "Initial
Sequence" (first-24-chip) hex column of Tables 17–20, all 4×50 = 200 primary
codes — by --self-test.

How it streams fast on a Pi (same three levers as gps_l1ca_tx)
────────────────────────────────────────────────────────────
1. PRECOMPUTE + LOOP: build the 100 ms buffer once, DMA bytes at runtime.
2. sc8 OVER THE WIRE: otw_format=sc8 halves USB payload.
3. NO STATUS UPDATES MID-RUN: UHD fastpath/underflow logging disabled; silent
   after start() (status writes under load actually *cause* underflows).
master_clock_rate is pinned equal to the sample rate (1:1, no FPGA resampling),
so samples-per-chip and the loop length stay exact.

Live tuning (retune while transmitting, via paramkit.live)
──────────────────────────────────────────────────────────
    gain        → UHD set_gain            (instant)
    amplitude   → multiply_const_cc.set_k (instant baseband digital scale)
Band, SVID, carrier, sample rate and otw are fixed for a run (restart to change).

CLI
───
    gal_e5_tx.py --band E5a --svid 1 --power -30 --rf on
    gal_e5_tx.py --band E5b --svid 12
    gal_e5_tx.py --self-test        # verify codes vs ICD check values, no hardware
    gal_e5_tx.py --describe-params  # paramkit JSON schema for the GUI
"""
